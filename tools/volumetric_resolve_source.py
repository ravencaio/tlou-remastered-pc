#!/usr/bin/env python3
"""Writes the volumetric light resolves of gow3_pc/gpu/shadps4/video_core/host_shaders: the port's
own translation of The Last of Us' resolves, as GLSL, with a path for the camera-ray grid of
vol_directional_integral.comp / vol_spot_integral.comp added (#55, PR #230):
vol_directional_resolve.frag from ps ad16e118 (sun, moon), vol_spot_resolve.frag from ps ca25dbad
(spotlights, flashlights).

  python tools/volumetric_resolve_source.py <cache>/CUSA00552/0x00000000ad16e118_0.spv
  python tools/volumetric_resolve_source.py <cache>/CUSA00552/0x00000000ca25dbad_0.spv

Needs spirv-cross (MSYS2 CLANG64: C:/msys64/clang64/bin, or --cross). Run it again when the
recompiler changes these shaders' interface (the port then logs that the replacement does not
match and keeps the translation, vk_volumetric_light.cpp). The original reconstruction stays as
it is for an image of epipolar lines; the new one runs only for the grid, which marks itself.
"""
import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HOST_SHADERS = ROOT / "gow3_pc/gpu/shadps4/video_core/host_shaders"

HEADER = """\
// SPDX-FileCopyrightText: Copyright 2026 gow3_pc contributors
// SPDX-License-Identifier: GPL-2.0-or-later

// gow3 24 Nov 2026 (The Last of Us Remastered #55): the {what} volumetric light's resolve
// (ps {hash}) as the shader recompiler translates it, decompiled, with one addition: when the
// image it reads holds the camera-ray grid of {integral} (cell (0,0) <= -1.99),
// the light is the grid's visibility, filtered over 6x6 cells weighted by distance and by depth
// agreement with this pixel{extent} (the technique is Guistevan's, PR #230). An image of the
// game's epipolar lines takes the original code.
// GENERATED by tools/volumetric_resolve_source.py from the translation; edit that script.
"""

VISIBILITY = """
// The grid's visibility at this pixel: 6x6 cells, by distance and by how close their ray's
// depth is to this pixel's (z, view units, capped at the grid's far limit).
float volumeVisibility(vec2 uv, float z, float far) {
    vec2 coord = clamp(uv * 512.0 - 0.5, vec2(0), vec2(511));
    ivec2 cell = ivec2(coord);
    vec2 f = fract(coord);
    float sum = 0.0, weight = 0.0;
    z = min(z, far);
    for (int y = -2; y <= 3; ++y) {
        for (int x = -2; x <= 3; ++x) {
            vec2 v = texelFetch(fs_img2, clamp(cell + ivec2(x, y), ivec2(0), ivec2(511)), 0).rg;
            float delta = (v.y - z) / max(0.08, 0.015 * abs(z));
            vec2 dist = vec2(x, y) - f;
            float w = exp(-0.5 * dot(dist, dist) / 1.44) / (1.0 + delta * delta * delta * delta);
            sum += w * (-2.0 - v.x);
            weight += w;
        }
    }
    return clamp(sum / max(weight, 1e-15), 0.0, 1.0);
}
"""

DIRECTIONAL_FUNCTIONS = """
float lightParam(uint offset, uint index) {
    return uintBitsToFloat(ssbo_1_1.data[offset + index]);
}

vec4 lightRow(uint offset, uint index) {
    return vec4(lightParam(offset, index), lightParam(offset, index + 1u),
                lightParam(offset, index + 2u), lightParam(offset, index + 3u));
}

vec2 lightInterval(uint offset, vec3 dir) {
    vec4 a = lightRow(offset, 104u), b = lightRow(offset, 108u), c = lightRow(offset, 112u);
    vec3 rate = vec3(dot(a.xyz, dir), dot(b.xyz, dir), dot(c.xyz, dir));
    vec3 inv = 1.0 / mix(rate, vec3(1e-12), lessThan(abs(rate), vec3(1e-12)));
    float capB = lightParam(offset, 116u), capC = lightParam(offset, 117u);
    float ta = -a.w * inv.x;
    vec2 tb = vec2(-b.w, capB) * inv.y, tc = vec2(-c.w, capC) * inv.z;
    float start = max(0.0, max(inv.x > 0.0 ? -100000.0 : ta,
                               max(min(tb.x, tb.y), min(tc.x, tc.y))));
    float end = min(lightParam(offset, 127u) / dir.z,
                    min(inv.x > 0.0 ? ta : 100000.0, min(max(tb.x, tb.y), max(tc.x, tc.y))));
    return vec2(start, max(start, end));
}
"""

DIRECTIONAL_GRID = """\
        precise float _667;
        precise float _711;
        if (texelFetch(fs_img2, ivec2(0), 0).x <= -1.99)
        {
            vec2 extent = lightInterval(buf0_dword_off, vec3(_221, _224, _164));
            _667 = clamp(_294 - extent.x, 0.0, max(0.0, extent.y - extent.x));
            _711 = volumeVisibility(vec2(_141, _143), _292, lightParam(buf0_dword_off, 127u));
        }
        else
        {
"""


def once(text, old, new):
    if text.count(old) != 1:
        sys.exit(f"Unexpected translation: {old!r} found {text.count(old)} times")
    return text.replace(old, new)


def directional(text):
    text = once(text, "\nvoid main()\n", DIRECTIONAL_FUNCTIONS + VISIBILITY + "\nvoid main()\n")
    # The reconstruction from _427 to _711, under the grid test; _667 and _711 are its results.
    start = "        precise float _427 = (-1.0) + _425;\n"
    end_line = re.search(r"        precise float _711 = \(1\.0 / _705\) \* _710;\n", text)
    if text.count(start) != 1 or not end_line:
        sys.exit("Unexpected translation: the reconstruction's bounds moved")
    a, b = text.index(start), end_line.end()
    region = text[a:b]
    region = once(region, "        precise float _667 = ", "        _667 = ")
    region = once(region, "        precise float _711 = ", "        _711 = ")
    region = "".join("    " + line if line.strip() else line for line in region.splitlines(True))
    return text[:a] + DIRECTIONAL_GRID + region + "        }\n" + text[b:]


def spot(text):
    # The spotlight's light along the ray stays the game's; only the visibility comes from the
    # grid (whose view depth is capped at 60000, vol_spot_integral.comp).
    text = once(text, "\nvoid main()\n", VISIBILITY + "\nvoid main()\n")
    return once(text, "        precise float _824 = (1.0 / _818) * _822;\n",
                "        precise float _824 = texelFetch(fs_img2, ivec2(0), 0).x <= -1.99\n"
                "                                 ? volumeVisibility(vec2(_153, _155), _267, 60000.0)\n"
                "                                 : (1.0 / _818) * _822;\n")


KINDS = {
    "ad16e118": ("vol_directional_resolve.frag", directional,
                 dict(what="sun's and moon's", hash="ad16e118",
                      integral="vol_directional_integral.comp",
                      extent=",\n// along the part of the ray inside the light's volume")),
    "ca25dbad": ("vol_spot_resolve.frag", spot,
                 dict(what="spotlights' and flashlights'", hash="ca25dbad",
                      integral="vol_spot_integral.comp", extent="")),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("spv", type=Path, help="the translated ad16e118 or ca25dbad, permutation 0")
    parser.add_argument("--cross", default="C:/msys64/clang64/bin/spirv-cross.exe")
    args = parser.parse_args()
    kind = next((k for k in KINDS if k in args.spv.name), None)
    if not kind:
        sys.exit("Give the ad16e118 or ca25dbad binary (by its cache name)")
    name, edit, words = KINDS[kind]
    with tempfile.TemporaryDirectory() as tmp:
        glsl = Path(tmp) / "resolve.frag"
        subprocess.run([args.cross, str(args.spv), "--vulkan-semantics", "--output", str(glsl)],
                       check=True)
        text = glsl.read_text(encoding="utf-8")
    # Only the 32-bit view of the constants is read: the 8/16/64-bit extensions and aliases go.
    text = re.sub(r"#extension GL_EXT_shader_(explicit_arithmetic_types_int(8|16)|(8|16)bit_storage)"
                  r" : require\n", "", text)
    text = re.sub(r"#if defined\(GL_ARB_gpu_shader_int64\)\n.*?#endif\n", "", text, flags=re.S)
    text = re.sub(r"layout\(set = 0, binding = 0, std430\) readonly buffer ssbo_1_\d+\n\{\n.*?\n\}"
                  r" ssbo_1_\d+;\n\n", "", text, flags=re.S)
    text = re.sub(r"struct (full_result_[iu]32x2|frexp_result_f32)\n\{\n.*?\n\};\n\n", "", text,
                  flags=re.S)
    for unused in ("ssbo_1_3", "ssbo_1_5", "ssbo_1_7", "uint16_t", "uint8_t", "int64"):
        if unused in text:
            sys.exit(f"The translation reads {unused}: update the script")
    text = once(text, "#version 450\n", HEADER.format(**words) + "\n#version 450\n")
    text = edit(text)
    out = HOST_SHADERS / name
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
